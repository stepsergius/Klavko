import AppKit
import CryptoKit
import KlavkoCore

/// Clipboard history: remembers what you copy (text, links, images, files) on this Mac
/// only, in ~/Library/Application Support/Klavko/Clipboard. Passwords and other concealed items
/// (marked so by password managers, nspasteboard.org) and copies made in ignored apps are never kept.
@MainActor
final class ClipboardManager: ObservableObject {
    @Published private(set) var history = ClipboardHistory()

    var isEnabled: () -> Bool = { true }
    /// Days to keep items (0: forever).
    var keepDays: () -> Int = { 30 }
    var ignoredApps: () -> [String] = { [] }
    /// Something new was copied (not Klavko's own paste from the history).
    var onCopied: () -> Void = {}

    static let maxItems = 1000
    /// Longer copies are kept cut to this length.
    private static let maxTextLength = 200_000
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private let folder: URL
    private var imagesFolder: URL { folder.appendingPathComponent("Images", isDirectory: true) }
    private var indexFile: URL { folder.appendingPathComponent("history.json") }

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        folder = support.appendingPathComponent("Klavko/Clipboard", isDirectory: true)
        lastChange = NSPasteboard.general.changeCount
        load()
    }

    /// Checks the clipboard twice a second (macOS has no notification for it).
    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    func imageURL(for item: ClipItem) -> URL? {
        item.imageName.map { imagesFolder.appendingPathComponent($0) }
    }

    // MARK: - Watching

    private func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        // Klavko itself is copying the selection for a moment (translation, layout of selected text).
        lastChange = change
        guard Date() >= SelectionConverter.borrowedUntil, change != SelectionConverter.restoredChangeCount else { return }
        guard isEnabled() else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier, ignoredApps().contains(bundleID) { return }
        guard let item = readItem(appName: app?.localizedName, bundleID: app?.bundleIdentifier) else { return }
        add(item)
        onCopied()
    }

    private func readItem(appName: String?, bundleID: String?) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ClipItem(kind: .files, text: paths, appName: appName, appBundleID: bundleID)
        }
        let text = pasteboard.string(forType: .string)
        // A picture copied in a browser comes with its address as text: keep the picture. Text that also
        // has a picture of itself (tables, rich text) stays text.
        let hasImage = pasteboard.availableType(from: [.png, .tiff]) != nil
        let textIsJustAddress = text.map { ClipItem.kind(ofText: $0) == .link || $0.hasPrefix("/") } ?? true
        if hasImage && textIsJustAddress, let item = imageItem(appName: appName, bundleID: bundleID) { return item }
        if let text, !text.isEmpty {
            let kept = text.count > Self.maxTextLength ? String(text.prefix(Self.maxTextLength)) : text
            return ClipItem(kind: ClipItem.kind(ofText: kept), text: kept, appName: appName, appBundleID: bundleID)
        }
        return imageItem(appName: appName, bundleID: bundleID)
    }

    private func imageItem(appName: String?, bundleID: String?) -> ClipItem? {
        guard let image = NSImage(pasteboard: pasteboard), let png = Self.png(image) else { return nil }
        let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        let name = String(hash.prefix(24)) + ".png"
        let url = imagesFolder.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: url.path) {
            try? FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
            guard (try? png.write(to: url)) != nil else { return nil }
        }
        let size = image.representations.first.map { "\($0.pixelsWide) × \($0.pixelsHigh)" } ?? ""
        return ClipItem(kind: .image, text: size, imageName: name, fingerprint: "image:" + hash,
                        appName: appName, appBundleID: bundleID)
    }

    private static func png(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    private func add(_ item: ClipItem) {
        let dropped = history.add(item, maxItems: Self.maxItems, maxAge: maxAge)
        deleteImages(of: dropped)
        scheduleSave()
    }

    private var maxAge: TimeInterval? {
        let days = keepDays()
        return days > 0 ? TimeInterval(days) * 86_400 : nil
    }

    // MARK: - Actions from the window

    /// Puts the item on the clipboard (and on top of the history).
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text, forType: .string)
        case .image:
            if let url = imageURL(for: item), let data = try? Data(contentsOf: url) {
                pasteboard.setData(data, forType: .png)
                if let image = NSImage(data: data), let tiff = image.tiffRepresentation {
                    pasteboard.setData(tiff, forType: .tiff)
                }
            }
        case .files:
            let urls = item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pasteboard.writeObjects(urls)
        }
        lastChange = pasteboard.changeCount
        history.touch(item.id)
        scheduleSave()
    }

    /// Copies the item and pastes it into the app in front.
    func paste(_ item: ClipItem) {
        copy(item)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            TextInjector.pressKey(9, flags: .maskCommand)  // ⌘V
        }
    }

    func togglePin(_ item: ClipItem) {
        history.togglePin(item.id)
        scheduleSave()
    }

    func remove(_ item: ClipItem) {
        if let removed = history.remove(item.id) { deleteImages(of: [removed]) }
        scheduleSave()
    }

    func clearUnpinned() {
        deleteImages(of: history.clearUnpinned())
        scheduleSave()
    }

    /// Applies a changed "keep for" setting.
    func prune() {
        deleteImages(of: history.prune(maxItems: Self.maxItems, maxAge: maxAge))
        scheduleSave()
    }

    // MARK: - Storage

    private func deleteImages(of items: [ClipItem]) {
        let stillUsed = Set(history.items.compactMap(\.imageName))
        for name in Set(items.compactMap(\.imageName)) where !stillUsed.contains(name) {
            try? FileManager.default.removeItem(at: imagesFolder.appendingPathComponent(name))
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexFile),
              let stored = try? JSONDecoder().decode(ClipboardHistory.self, from: data) else { return }
        history = stored
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated { self?.save() }
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    private func save() {
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            let data = try JSONEncoder().encode(history)
            try data.write(to: indexFile, options: [.atomic, .completeFileProtection])
        } catch {
            Log.engine.error("Clipboard history not saved: \(error.localizedDescription, privacy: .public)")
        }
    }
}
